    (r"гряз[ьн][а-я]*|мусор", "грязь/санитария"),
    (r"жалоб[а-я]*|претензи[а-я]*|возмущен[а-я]*", "прямая жалоба"),
    (r"сбо[йи]|завис[а-я]*|тормозит|лагает", "технический сбой"),
