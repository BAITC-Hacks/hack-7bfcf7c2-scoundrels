# ФУНКЦИЯ КЛАССИФИКАЦИИ
# ---------------------------------------------------------------------------

def classify_text_by_rules(text: str) -> ClassificationResult:
    """
    Классифицирует текст обращения и формирует адресный черновик ответа.
    
    Приоритет:
    1. ЖАЛОБА (высокий приоритет: сбои, холодная еда, очереди требуют оперативной реакции)
    2. СПРАВКА (запросы документов, локаций, расписания)
    3. ДРУГОЕ (запись на прием, консультации, прочее)
    """
    lower = text.lower()

    # 1. Проверка на ЖАЛОБУ
    for pattern, name in PATTERNS_COMPLAINT:
        if re.search(pattern, lower):
            if "столов" in lower or "еда" in lower or "холодн" in lower:
                return ClassificationResult(
                    category=Category.COMPLAINT.value,
                    draft_reply=SPECIFIC_DRAFTS["столовая"],
                    confidence=0.98,
                    matched_pattern=f"complaint: {name}"
                )
            if "wi-fi" in lower or "вайфай" in lower or "интернет" in lower:
                return ClassificationResult(
                    category=Category.COMPLAINT.value,
                    draft_reply=SPECIFIC_DRAFTS["wifi"],
                    confidence=0.98,
                    matched_pattern=f"complaint: {name}"
                )
            return ClassificationResult(
                category=Category.COMPLAINT.value,
                draft_reply=DEFAULT_DRAFTS[Category.COMPLAINT.value],
                confidence=0.90,
                matched_pattern=f"complaint: {name}"
            )

    # 2. Проверка на СПРАВКУ
    for pattern, name in PATTERNS_REFERENCE:
        if re.search(pattern, lower):
            if "справк" in lower or "учеб" in lower:
                return ClassificationResult(
                    category=Category.REFERENCE.value,
                    draft_reply=SPECIFIC_DRAFTS["справка_учеба"],
                    confidence=0.98,
                    matched_pattern=f"reference: {name}"
                )
            if "парковк" in lower:
                return ClassificationResult(
                    category=Category.REFERENCE.value,
                    draft_reply=SPECIFIC_DRAFTS["парковка"],
                    confidence=0.98,
                    matched_pattern=f"reference: {name}"
                )
            return ClassificationResult(
                category=Category.REFERENCE.value,
                draft_reply=DEFAULT_DRAFTS[Category.REFERENCE.value],
                confidence=0.88,
                matched_pattern=f"reference: {name}"
            )

    # 3. Проверка на ДРУГОЕ (запись, консультация)
    for pattern, name in PATTERNS_OTHER:
        if re.search(pattern, lower):
            if "консультац" in lower or "записат" in lower:
                return ClassificationResult(
                    category=Category.OTHER.value,
                    draft_reply=SPECIFIC_DRAFTS["консультация"],
                    confidence=0.95,
                    matched_pattern=f"other: {name}"
                )
            return ClassificationResult(
                category=Category.OTHER.value,
                draft_reply=DEFAULT_DRAFTS[Category.OTHER.value],
                confidence=0.85,
                matched_pattern=f"other: {name}"
            )

    # Дефолтная ветка
    return ClassificationResult(
        category=Category.OTHER.value,
        draft_reply=DEFAULT_DRAFTS[Category.OTHER.value],
        confidence=0.60,
        matched_pattern="fallback: generic"
    )
