from typing import NamedTuple, Optional


class Category(str, Enum):
    """Категории обращений строго по регламенту кейса."""
    REFERENCE = "справка"
    COMPLAINT = "жалоба"
    OTHER = "другое"


class ClassificationResult(NamedTuple):
    category: str
    draft_reply: str
    confidence: float
    matched_pattern: Optional[str] = None


