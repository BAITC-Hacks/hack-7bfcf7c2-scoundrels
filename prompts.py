def build_user_prompt(message: str) -> str:
    """Формирование промпта для конкретного пользовательского сообщения."""
    return f"""Классифицируй следующее обращение и подготовь черновик ответа:
"{message}"

JSON:"""


def parse_and_validate_llm_response(raw_text: str) -> Tuple[str, str]:
    """
    Парсит ответ от LLM, очищает от возможных markdown-тегов и валидирует категорию.
    
    Returns:
        tuple[str, str]: (category, draft_reply)
    """
    cleaned = raw_text.strip()
    # Удаление обертки ```json ... ```
    if cleaned.startswith("```"):
        cleaned = re.sub(r"^```(?:json)?\s*", "", cleaned)
        cleaned = re.sub(r"\s*```$", "", cleaned)
    
    data = json.loads(cleaned)
    category = str(data.get("category", "другое")).strip().lower()
    if category not in ["справка", "жалоба", "другое"]:
        category = "другое"
    
    draft = str(data.get("draft", "")).strip()
    if not draft:
        draft = "Здравствуйте! Ваше обращение принято в обработку нашей службой поддержки."
        
    return category, draft
